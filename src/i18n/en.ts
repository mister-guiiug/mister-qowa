const s = (n: number) => (Number(n) === 1 ? "" : "s");

const enOrdinal = (n: number) => {
  const suf = ["th", "st", "nd", "rd"];
  const k = n % 100;
  return `${n}${suf[(k - 20) % 10] || suf[k] || suf[0]}`;
};

